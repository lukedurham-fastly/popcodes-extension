const input = document.getElementById("code-input");
const result = document.getElementById("result");
const recentsList = document.getElementById("recents-list");

const RECENTS_KEY = "recentLookups";
const MAX_RECENTS = 5;
// Three characters is an IATA code lookup; anything longer is a word search.
const CODE_LENGTH = 3;
const MAX_SEARCH_RESULTS = 8;

let airports = null;
let pops = {};
let siteCodes = {};
let overrideCodes = new Set();
let searchIndex = [];

Promise.all([
  fetch("../data/airports.json").then((response) => response.json()),
  fetch("../data/metro-codes.json").then((response) => response.json()),
  fetch("../data/fastly-codes.json").then((response) => response.json()),
  // pops.json is generated at package time (scripts/fetch-pops.mjs) and may be
  // absent in a dev checkout — treat that as "no POPs", not a load failure.
  fetch("../data/pops.json")
    .then((response) => response.json())
    .catch(() => ({})),
  // site-codes.json maps POP -> Grafana site codes (generated by
  // data/generate-site-codes.py); POPs missing from it fall back to ICAO.
  fetch("../data/site-codes.json")
    .then((response) => response.json())
    .catch(() => ({})),
])
  .then(([airportData, metroCodes, fastlyCodes, popData, siteCodeData]) => {
    // metro-codes.json and fastly-codes.json are hand-maintained overrides for
    // codes the canonical airport dataset will never contain (IATA metro-area
    // codes and Fastly-internal placeholder codes) — merged on top so they
    // resolve the same way a real airport code would.
    airports = { ...airportData, ...metroCodes, ...fastlyCodes };
    overrideCodes = new Set([...Object.keys(metroCodes), ...Object.keys(fastlyCodes)]);
    pops = popData;
    siteCodes = siteCodeData;
    searchIndex = buildSearchIndex();
    lookup(input.value);
  })
  .catch(() => {
    result.textContent = "Failed to load airport data";
  })
  .then(() => renderRecents())
  .finally(() => {
    window.__popcodesReady = true;
  });

function lookup(rawValue) {
  const code = rawValue.toUpperCase();

  if (code !== rawValue) {
    input.value = code;
  }

  if (code.length < CODE_LENGTH) {
    result.textContent = "";
    return null;
  }

  if (!airports) {
    return null;
  }

  if (code.length > CODE_LENGTH) {
    return search(code);
  }

  const entry = buildEntry(code);

  if (!entry) {
    result.textContent = `No airport found for "${code}"`;
    return null;
  }

  showResult(entry);
  return entry;
}

function buildEntry(code) {
  const airport = airports[code];

  if (!airport) {
    return null;
  }

  return {
    code,
    city: airport.city,
    country: airport.country,
    override: overrideCodes.has(code),
  };
}

// Lowercase and strip diacritics so "sao paulo" finds "São Paulo".
function normalize(text) {
  return text.normalize("NFD").replace(/\p{M}/gu, "").toLowerCase();
}

// Searches by city, plus the Fastly POP name (which can differ from the
// airport's city, e.g. "Sydney" vs "Sydney (Mascot)") and the ICAO code.
function buildSearchIndex() {
  return Object.entries(airports).map(([code, airport]) => ({
    code,
    haystack: normalize(`${airport.city} ${pops[code]?.name ?? ""}`),
    icao: airport.icao,
    isPop: Boolean(pops[code]),
  }));
}

function search(rawQuery) {
  const query = normalize(rawQuery);

  const matches = searchIndex
    .filter((item) => item.haystack.includes(query) || item.icao === rawQuery)
    .sort(
      (a, b) =>
        b.isPop - a.isPop ||
        b.haystack.startsWith(query) - a.haystack.startsWith(query) ||
        a.code.localeCompare(b.code)
    );

  if (matches.length === 0) {
    result.textContent = `No airport found for "${rawQuery}"`;
    return null;
  }

  const entries = matches.slice(0, MAX_SEARCH_RESULTS).map((item) => buildEntry(item.code));
  renderSearchResults(entries, matches.length);

  // A lone match is what Enter selects; with several, the user picks one.
  return matches.length === 1 ? entries[0] : null;
}

function renderSearchResults(entries, total) {
  const list = document.createElement("ul");
  list.className = "search-results";

  for (const entry of entries) {
    const item = document.createElement("li");
    item.className = "search-results__item";

    const label = document.createElement("span");
    label.className = "recents__label";
    // Include the ICAO code so a match on it (e.g. YBBN) is visible in the row.
    const icao = airports[entry.code]?.icao;
    label.textContent =
      `${entry.code} — ${entry.city}, ${entry.country}` + (icao ? ` (${icao})` : "");
    item.appendChild(label);

    if (pops[entry.code]) {
      item.appendChild(renderRecentPopIcon());
      if (pops[entry.code].shield) {
        item.appendChild(createShieldIcon(pops[entry.code].shield));
      }
    }

    item.addEventListener("click", () => selectEntry(entry));
    list.appendChild(item);
  }

  result.replaceChildren(list);

  if (total > entries.length) {
    const more = document.createElement("div");
    more.className = "search-results__more";
    more.textContent = `${total - entries.length} more — keep typing to narrow`;
    result.appendChild(more);
  }
}

async function selectEntry(entry) {
  showResult(entry);
  input.value = "";
  await addRecent(entry);
}

function showResult(entry) {
  result.textContent = `${entry.code} — ${entry.city}, ${entry.country}`;

  const pop = pops[entry.code];
  if (entry.override || pop) {
    result.appendChild(renderBadges(entry, pop));
  }
}

// Shared by renderPopBadges() (result area) and renderList() (recents list)
// so both places render the exact same Fastly icon markup. The <img> alt is
// always empty because the accessible label lives on whichever element wraps
// the icon at the call site.
function renderFastlyIcon() {
  const icon = document.createElement("img");
  icon.className = "pop-badge__icon";
  icon.src = "../icons/icon-small.svg";
  icon.alt = "";
  return icon;
}

// Shared by every badge in renderBadges() so each one only has to specify
// what's different: its class suffix, visible content, and accessible label.
function createBadge(className, content, label) {
  const badge = document.createElement("span");
  badge.className = `pop-badge ${className}`;
  badge.title = label;
  badge.setAttribute("aria-label", label);
  badge.append(...[].concat(content));
  return badge;
}

// Small icon-only indicator (shield) with a tooltip. `paths` is
// static markup defined in this file, never data from pops.json.
function createIconBadge(className, paths, label) {
  const icon = document.createElement("span");
  icon.className = `pop-icon ${className}`;
  icon.title = label;
  icon.setAttribute("aria-label", label);
  // The <title> inside the SVG is a fallback tooltip; pointer-events:none on the
  // SVG (see CSS) makes the hover land on the span, which carries the title.
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", "14");
  svg.setAttribute("height", "14");
  svg.innerHTML = `<title></title>${paths}`;
  svg.querySelector("title").textContent = label;
  icon.appendChild(svg);
  return icon;
}

function createShieldIcon(shield) {
  return createIconBadge(
    "pop-icon--shield",
    '<path d="M12 2 4 5v6c0 5 3.4 9.4 8 11 4.6-1.6 8-6 8-11V5l-8-3z"/>',
    shield
  );
}

const NEARBY_POP_COUNT = 50;
const MAP_SELECTED_COLOR = "#FF282D";
const MAP_NEARBY_COLOR = "#1E6FFF";

function distanceKm(a, b) {
  const rad = Math.PI / 180;
  const dLat = (b.latitude - a.latitude) * rad;
  const dLon = (b.longitude - a.longitude) * rad;
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(a.latitude * rad) * Math.cos(b.latitude * rad) * Math.sin(dLon / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(h));
}

// Default shield POPs (those with a `shield` name in the POP list) get a Maki
// star on their pin; geojson.io's simplestyle reads `marker-symbol`.
function mapFeature(code, pop, color) {
  const properties = {
    title: `${code} - ${pop.name}`,
    "marker-color": color,
  };
  if (pop.shield) properties["marker-symbol"] = "star";
  return {
    type: "Feature",
    properties,
    geometry: {
      type: "Point",
      coordinates: [Number(pop.longitude.toFixed(4)), Number(pop.latitude.toFixed(4))],
    },
  };
}

// Google Maps URLs can't set pin colours or show several labelled pins, so the
// map is a geojson.io link carrying the pins as GeoJSON in the URL fragment
// (never sent to a server by us — the popup itself still makes no requests).
function buildMapUrl(code, pop) {
  const nearby = Object.entries(pops)
    .filter(([otherCode]) => otherCode !== code)
    .map(([otherCode, other]) => ({ otherCode, other, km: distanceKm(pop, other) }))
    .sort((a, b) => a.km - b.km)
    .slice(0, NEARBY_POP_COUNT);

  const geojson = {
    type: "FeatureCollection",
    features: [
      ...nearby.map(({ otherCode, other }) => mapFeature(otherCode, other, MAP_NEARBY_COLOR)),
      mapFeature(code, pop, MAP_SELECTED_COLOR),
    ],
  };
  // Base64 because geojson.io truncates a plain-JSON fragment at the "#" in the
  // hex colours. It doesn't UTF-8 decode, so non-ASCII is \u-escaped first.
  const ascii = JSON.stringify(geojson).replace(
    /[\u0080-\uffff]/g,
    (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`
  );
  return `https://geojson.io/#data=data:application/json;base64,${encodeURIComponent(btoa(ascii))}`;
}

function renderBadges(entry, pop) {
  const badges = document.createElement("div");
  badges.className = "pop-badges";

  if (entry.override) {
    badges.appendChild(
      createBadge(
        "pop-badge--override",
        "Not an IATA airport",
        "City/country data is hand-maintained, not from the IATA airport dataset"
      )
    );
  }

  if (!pop) {
    return badges;
  }

  // The POP's internal code is the Grafana site code(s) from site-codes.json,
  // falling back to the airport's ICAO code (e.g. BNE -> YBBN). Only worth
  // showing when it differs from the POP code.
  const icao = airports[entry.code]?.icao;
  const internalCodes = (siteCodes[entry.code] ?? (icao ? [icao] : [])).filter(
    (code) => code !== entry.code
  );
  if (internalCodes.length) {
    const list = internalCodes.join(", ");
    badges.appendChild(
      createBadge("pop-badge--internal", list, `Internal (site) code: ${list}`)
    );
  }

  badges.appendChild(
    createBadge("pop-badge--fastly", [renderFastlyIcon(), "Fastly POP"], "Official Fastly POP")
  );

  if (pop.metro) {
    badges.appendChild(createBadge("pop-badge--metro", "Metro", "Metro POP"));
  }

  if (pop.shield) {
    badges.appendChild(createShieldIcon(pop.shield));
  }

  const mapLink = document.createElement("a");
  mapLink.className = "pop-map-link";
  mapLink.href = buildMapUrl(entry.code, pop);
  mapLink.target = "_blank";
  mapLink.rel = "noopener";
  const mapLabel = `Open ${pop.name} POP location on a map, with nearby POPs`;
  mapLink.title = mapLabel;
  mapLink.setAttribute("aria-label", mapLabel);
  mapLink.innerHTML =
    '<svg viewBox="0 0 24 24" width="14" height="14" aria-hidden="true">' +
    '<path fill="#FF282D" d="M12 2a7 7 0 0 0-7 7c0 5.25 7 13 7 13s7-7.75 7-13a7 7 0 0 0-7-7zm0 9.5a2.5 2.5 0 1 1 0-5 2.5 2.5 0 0 1 0 5z"/>' +
    "</svg>";
  badges.appendChild(mapLink);

  return badges;
}

async function getRecents() {
  const data = await browser.storage.local.get(RECENTS_KEY);
  return data[RECENTS_KEY] || [];
}

function setRecents(recents) {
  return browser.storage.local.set({ [RECENTS_KEY]: recents });
}

async function addRecent(entry) {
  const recents = await getRecents();
  const deduped = recents.filter((r) => r.code !== entry.code);
  deduped.unshift(entry);
  const trimmed = deduped.slice(0, MAX_RECENTS);
  await setRecents(trimmed);
  renderList(trimmed);
}

async function renderRecents() {
  renderList(await getRecents());
}

function renderList(recents) {
  recentsList.innerHTML = "";

  for (const entry of recents) {
    const item = document.createElement("li");
    item.className = "recents__item";

    const label = document.createElement("span");
    label.className = "recents__label";
    label.textContent = `${entry.code} — ${entry.city}, ${entry.country}`;
    item.appendChild(label);

    // pops.json is absent in a dev checkout, so pops may be {} — that's
    // "no POPs", not an error, same as showResult() already treats it.
    if (pops[entry.code]) {
      item.appendChild(renderRecentPopIcon());
      if (pops[entry.code].shield) {
        item.appendChild(createShieldIcon(pops[entry.code].shield));
      }
    }

    item.appendChild(renderDeleteButton(entry));

    item.addEventListener("click", () => {
      input.value = entry.code;
      showResult(entry);
    });
    recentsList.appendChild(item);
  }
}

function renderRecentPopIcon() {
  const wrapper = document.createElement("span");
  wrapper.className = "recents__pop-icon";
  wrapper.title = "Fastly POP";
  wrapper.setAttribute("aria-label", "Fastly POP");
  wrapper.appendChild(renderFastlyIcon());
  return wrapper;
}

function renderDeleteButton(entry) {
  const button = document.createElement("button");
  button.type = "button";
  button.className = "recents__delete";
  const label = `Remove ${entry.code} from recent lookups`;
  button.title = label;
  button.setAttribute("aria-label", label);
  // Feather Icons "trash-2" (MIT), inlined — no external asset/network fetch.
  button.innerHTML =
    '<svg viewBox="0 0 24 24" width="12" height="12" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
    '<polyline points="3 6 5 6 21 6"></polyline>' +
    '<path d="M19 6l-1 14a2 2 0 0 1-2 2H8a2 2 0 0 1-2-2L5 6m3 0V4a2 2 0 0 1 2-2h4a2 2 0 0 1 2 2v2"></path>' +
    '<line x1="10" y1="11" x2="10" y2="17"></line>' +
    '<line x1="14" y1="11" x2="14" y2="17"></line>' +
    "</svg>";

  button.addEventListener("click", async (event) => {
    event.stopPropagation();
    const recents = await getRecents();
    const updated = recents.filter((r) => r.code !== entry.code);
    await setRecents(updated);
    renderList(updated);
  });

  return button;
}

input.addEventListener("input", () => lookup(input.value));

input.addEventListener("keydown", async (event) => {
  if (event.key !== "Enter") {
    return;
  }

  const entry = lookup(input.value);

  if (entry) {
    await selectEntry(entry);
  }

  // Several search matches stay on screen so the user can pick one.
  if (entry || input.value.length <= CODE_LENGTH) {
    input.value = "";
  }
});
